/**
 * Turns the Android-style strings.xml files of `src/commonMain/strings/values-xx` into
 * Kotlin, so both apps show the same texts and a screen can switch language on its own
 * (the Lessons tab follows the "Translate To" language).
 */
abstract class GenerateStrings : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val source: DirectoryProperty

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        val tables = source.get().asFile.listFiles().orEmpty()
            .filter { it.isDirectory && (it.name == "values" || it.name.startsWith("values-")) }
            .sortedBy { it.name }
            .associate { it.name.removePrefix("values").removePrefix("-") to readStrings(File(it, "strings.xml")) }
        val defaults = tables[""] ?: error("src/commonMain/strings/values/strings.xml is missing")
        val names = defaults.keys.toList()
        for ((language, table) in tables) {
            val unknown = table.keys - defaults.keys
            if (unknown.isNotEmpty()) logger.warn("values-$language has strings that values/ lacks: $unknown")
        }
        val code = buildString {
            appendLine("// Generated by the generateStrings task from src/commonMain/strings. Do not edit.")
            appendLine("package dev.nefrin.wordsmap.resources")
            appendLine()
            appendLine("/** The interface texts, one per string of values/strings.xml. Shown with [stringResource]. */")
            appendLine("object Strings {")
            names.forEachIndexed { index, name -> appendLine("    val `$name` = StringRes($index)") }
            appendLine("}")
            appendLine()
            appendLine("internal val defaultStrings: Array<String> = arrayOf(")
            names.forEach { appendLine("    ${literal(defaults.getValue(it))},") }
            appendLine(")")
            appendLine()
            appendLine("/** Translations by language code, null where a text is not translated. */")
            appendLine("internal val translatedStrings: Map<String, Array<String?>> = mapOf(")
            for ((language, table) in tables) {
                if (language.isEmpty()) continue
                appendLine("    \"$language\" to arrayOf(")
                names.forEach { name -> appendLine("        ${table[name]?.let(::literal) ?: "null"},") }
                appendLine("    ),")
            }
            appendLine(")")
        }
        val file = output.get().asFile.resolve("dev/nefrin/wordsmap/resources/Strings.kt")
        file.parentFile.mkdirs()
        file.writeText(code)
    }

    private fun readStrings(file: File): Map<String, String> {
        if (!file.exists()) return emptyMap()
        val document = DocumentBuilderFactory.newInstance().newDocumentBuilder().parse(file)
        val nodes = document.getElementsByTagName("string")
        return buildMap {
            for (i in 0 until nodes.length) {
                val element = nodes.item(i) as Element
                put(element.getAttribute("name"), androidText(element.textContent))
            }
        }
    }

    // Applies Android's rules: whitespace collapses unless the text is in double quotes,
    // and a backslash escapes the next character (\n, \t and \uXXXX included).
    private fun androidText(raw: String): String {
        val quoted = raw.length >= 2 && raw.startsWith("\"") && raw.endsWith("\"")
        val text = if (quoted) raw.substring(1, raw.length - 1) else raw.trim().replace(Regex("\\s+"), " ")
        val out = StringBuilder()
        var i = 0
        while (i < text.length) {
            val c = text[i]
            if (c != '\\' || i + 1 == text.length) {
                out.append(c)
                i++
                continue
            }
            when (val next = text[i + 1]) {
                'n' -> out.append('\n')
                't' -> out.append('\t')
                'u' -> {
                    out.append(text.substring(i + 2, i + 6).toInt(16).toChar())
                    i += 4
                }
                else -> out.append(next)
            }
            i += 2
        }
        return out.toString()
    }

    private fun literal(text: String): String = buildString {
        append('"')
        for (c in text) {
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                '\n' -> append("\\n")
                '\t' -> append("\\t")
                '\r' -> append("\\r")
                else -> append(c)
            }
        }
        append('"')
    }
}

/**
 * Lists every file under `composeResources/files`. Compose resources can read a file but not
 * list a folder, and the app finds its lessons, texts and word files by listing folders.
 */
abstract class GenerateAssetIndex : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val source: DirectoryProperty

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = source.get().asFile
        val paths = root.walkTopDown()
            .filter { it.isFile && !it.name.startsWith(".") }
            .map { it.relativeTo(root).invariantSeparatorsPath }
            .sorted()
            .toList()
        val code = buildString {
            appendLine("// Generated by the generateAssetIndex task from composeResources/files. Do not edit.")
            appendLine("package dev.nefrin.wordsmap.resources")
            appendLine()
            appendLine("internal val assetPaths: List<String> = listOf(")
            paths.forEach { appendLine("    \"${it.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")}\",") }
            appendLine(")")
        }
        val file = output.get().asFile.resolve("dev/nefrin/wordsmap/resources/AssetIndex.kt")
        file.parentFile.mkdirs()
        file.writeText(code)
    }
}

val generateStrings = tasks.register<GenerateStrings>("generateStrings") {
    source = layout.projectDirectory.dir("src/commonMain/strings")
    output = layout.buildDirectory.dir("generated/wordsmap/strings")
}

val generateAssetIndex = tasks.register<GenerateAssetIndex>("generateAssetIndex") {
    source = layout.projectDirectory.dir("src/commonMain/composeResources/files")
    output = layout.buildDirectory.dir("generated/wordsmap/assets")
}

